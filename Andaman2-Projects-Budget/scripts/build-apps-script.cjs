const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const image=(file,type)=>'data:'+type+';base64,'+fs.readFileSync(path.join(root,'dist/report-editor',file)).toString('base64');
let html=read('dist/report-editor/index.html');
html=html.replace('<link rel="stylesheet" href="styles.css">',()=>'<style>'+read('dist/report-editor/styles.css')+'</style>');
html=html.replace('<link rel="stylesheet" href="guide.css">',()=>'<style>'+read('dist/report-editor/guide.css')+'</style>');
const scripts=['supabase.js','config.js','core.js','print.js','guide.js','app.js'];
for(const script of scripts)html=html.replace('  <script defer src="'+script+'"></script>\n','');
const scriptHtml=scripts.map(file=>'<script>\n'+read('dist/report-editor/'+file).replace(/<\/script/gi,'<\\/script')+'\n</script>').join('\n');
html=html.replace('</body>',()=>scriptHtml+'\n</body>');
html=html.replaceAll('logo.jpg',image('logo.jpg','image/jpeg')).replaceAll('garuda.png',image('garuda.png','image/png'));
fs.writeFileSync(path.join(root,'apps-script/Index.html'),html);
console.log('Created apps-script/Index.html (embedded CSS, JS, logo and Garuda)');
