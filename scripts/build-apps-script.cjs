const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const src='dist/report-editor/';
const publicConfig=read('apps-script/Config.html').match(/<script>([\s\S]*?)<\/script>/)[1];
fs.writeFileSync(path.join(root,src+'config.js'),'// Generated from apps-script/Config.html; edit that file and rebuild.\n'+publicConfig);
let html=read(src+'index.html').replace('<head>','<head>\n  <base target="_top">');
for(const name of ['styles.css','guide.css'])html=html.replace('<link rel="stylesheet" href="'+name+'">',()=>'<style>'+read(src+name)+'</style>');
const scripts=['supabase.js','sdk-loader.js','config.js','core.js','print.js','guide.js','app.js'];
for(const name of scripts)html=html.replace('  <script defer src="'+name+'"></script>\n','');
const inlined=scripts.map(name=>{
  if(name==='config.js')return '<?!= includePublicConfig_(); ?>';
  let code=read(src+name);
  // An explicit browser export also works when the host isolates script variables.
  if(name==='supabase.js'){
    if(!code.startsWith('var supabase='))throw Error('Unexpected SDK bundle export; inspect before rebuilding');
    code=code.replace(/^var supabase=/,'window.supabase=');
  }
  return '<script id="andaman-'+name.replace('.js','')+'">\n'+code.replace(/<\/script/gi,'<\\/script')+'\n</script>';
}).join('\n');
html=html.replace('</body>',()=>inlined+'\n</body>');
for(const [file,mime] of [['logo.jpg','image/jpeg'],['garuda.png','image/png']])html=html.replaceAll(file,'data:'+mime+';base64,'+fs.readFileSync(path.join(root,src,file)).toString('base64'));
fs.writeFileSync(path.join(root,'apps-script/Index.html'),html);
// Keep server calculations identical to the frontend; generated Core.gs has no browser dependency.
let core=read(src+'core.js').replace('(function (root) {','var AndamanReportCore = (function () {');
core=core.replace(/  function uuid\(\) \{[^\n]*\}/,'  function uuid() { return Utilities.getUuid(); }');
core=core.replace("  if(typeof module!=='undefined'&&module.exports)module.exports=api;\n  root.ReportCore=api;\n})(typeof window!=='undefined'?window:globalThis);",'  return api;\n})();');
fs.writeFileSync(path.join(root,'apps-script/Core.gs'),'// Generated by node scripts/build-apps-script.cjs from the same frontend core.\n'+core);
console.log('Built Apps Script Index.html and Core.gs.');
